import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { getPool } from "../db.js";
import { createApp } from "../app.js";

// Explicit opt-in live smoke test. Only this run's generated account is removed.
const pool = getPool();
const server = createApp().listen(0, "127.0.0.1");
await new Promise((resolve) => server.once("listening", resolve));
const base = `http://127.0.0.1:${server.address().port}/api`;
const email = `smoke-${randomUUID()}@example.test`;
let token;
const request = async (url, method = "GET", body) => {
  const response = await fetch(base + url, { method,
    headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const result = await response.json();
  assert.ok(response.ok, `${method} ${url} returned ${response.status}`);
  return result;
};
try {
  assert.equal((await request("/health")).database, "connected");
  const password = randomUUID();
  const registered = await request("/auth/register", "POST", { nama: "Temporary integration test", email, password });
  assert.ok(registered.user.id);
  token = (await request("/auth/login", "POST", { email, password })).token;
  const { course } = await request("/courses", "POST", { name: "Temporary test course" });
  const { task } = await request("/tasks", "POST", { judul: "Temporary deadline test", mata_kuliah_id: course.id,
    deadline: new Date(Date.now() + 3600000).toISOString() });
  assert.equal((await request("/tasks")).tasks[0].deadline_category, "urgent");
  await request(`/tasks/${task.id}`, "PUT", { status: "selesai" });
  assert.equal((await request("/tasks")).tasks[0].deadline_category, "completed");
  await request(`/courses/${course.id}`, "DELETE");
  assert.equal((await request("/tasks")).tasks.length, 0);
  console.log("Live Neon smoke test passed: health, register, login, courses, tasks, reminders, completion, and cascade deletion.");
} catch (error) {
  console.error("Live Neon smoke test failed:", error.code || error.message.split("\n")[0]);
  process.exitCode = 1;
} finally {
  // Email is generated by this run, so unrelated user records are never targeted.
  await pool.query("DELETE FROM users WHERE email = $1", [email]);
  await new Promise((resolve) => server.close(resolve));
  await pool.end();
}
